"""DisgaeaD2.ini: lets DisgaeaD2Recomp.exe start by itself (double-click, desktop shortcut) after the launcher
has prepared the game. The launcher rewrites it next to the executable every time it runs the game; port/main.cpp
reads it when the executable is started without arguments.

Format, UTF-8, one entry per line: eboot=, cwd=, iso=, env.NAME=value, unset.NAME
"""
from pathlib import Path
import os

# Settings the in-game options menu now owns (window size, V-Sync) and per-run diagnostics never belong here.
SKIP_NAMES = {'D2_OUTPUT_WIDTH', 'D2_OUTPUT_HEIGHT', 'D2_VSYNC', 'D2_GAME_ISO', 'D2_STOP_AFTER_SECONDS',
              'D2_VULKAN_FORCE_INIT_FAIL', 'D2_VULKAN_DUMP_DIR', 'D2_VULKAN_STATS', 'D2_VULKAN_VALIDATION',
              'D2_CONSOLE'}
SKIP_PREFIXES = ('D2_CAPTURE', 'D2_DRAW_CAPTURE', 'RSX_CAP')


def config_path(exe):
    return Path(exe).parent / 'DisgaeaD2.ini'


def build_player_config(elf, cwd, iso, env, base_env, clear=()):
    """Text of the file. `env` is what the game is launched with, `base_env` the launcher's own environment: only
    differences are stored, so nothing machine-specific is frozen into the file."""
    lines = ['# Generated by the launcher. Lets DisgaeaD2Recomp.exe start without arguments.',
             'eboot=' + str(elf), 'cwd=' + str(cwd)]
    if iso:
        lines.append('iso=' + str(iso))
    for name in sorted(env):
        value = env[name]
        if name in SKIP_NAMES or name.startswith(SKIP_PREFIXES) or '\n' in value or '=' in name:
            continue
        if base_env.get(name) != value:
            lines.append('env.' + name + '=' + value)
    for name in sorted(clear):
        if name in base_env and name not in env and name not in SKIP_NAMES:
            lines.append('unset.' + name)
    return '\n'.join(lines) + '\n'


def write_player_config(exe, elf, cwd, iso, env, base_env=None, clear=()):
    """Writes the file next to `exe`. Never raises: it is a convenience, not a reason to stop the game."""
    try:
        text = build_player_config(elf, cwd, iso, env, os.environ if base_env is None else base_env, clear)
        target = config_path(exe)
        temporary = target.with_suffix('.ini.tmp')
        temporary.write_text(text, encoding='utf-8', newline='\n')
        os.replace(temporary, target)
        return target
    except OSError:
        return None
