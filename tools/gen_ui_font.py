#!/usr/bin/env python3
"""Generate port/vulkan/ui_font.inc: a small glyph atlas for the in-game options overlay.

Usage: python tools/gen_ui_font.py [path-to-ttf] [pixel-size]
The font is rasterised once here (needs Pillow) and shipped as run-length encoded 4-bit alpha, so the game
itself needs no font files and no extra libraries. Default font: DejaVu Sans (free licence, Bitstream Vera derivative).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
px = int(sys.argv[2]) if len(sys.argv) > 2 else 26
codes = list(range(32, 127)) + list(range(160, 256))
font = ImageFont.truetype(ttf, px)
asc, desc = font.getmetrics()
cell_h = asc + desc + 2
cell_w = max(int(font.getlength(chr(c))) for c in codes) + 4
cols = 16
rows = (len(codes) + 1 + cols - 1) // cols  # +1: last cell is solid white (for rectangles)
aw, ah = cols * cell_w, rows * cell_h
img = Image.new("L", (aw, ah), 0)
d = ImageDraw.Draw(img)
adv = []
for i, c in enumerate(codes):
    x, y = (i % cols) * cell_w, (i // cols) * cell_h
    d.text((x + 2, y), chr(c), font=font, fill=255)
    adv.append(int(round(font.getlength(chr(c)))))
n = len(codes)
wx, wy = (n % cols) * cell_w, (n // cols) * cell_h
d.rectangle([wx, wy, wx + cell_w - 1, wy + cell_h - 1], fill=255)
pix = [min(15, (v + 8) // 17) for v in img.tobytes()]
out, i = [], 0
while i < len(pix):
    v, run = pix[i], 1
    while i + run < len(pix) and pix[i + run] == v and run < 16:
        run += 1
    out.append((v << 4) | (run - 1))
    i += run
with open("port/vulkan/ui_font.inc", "w") as f:
    f.write("// Generated by tools/gen_ui_font.py - do not edit. Font: %s, %dpx.\n" % (ttf.split('/')[-1], px))
    f.write("// 4-bit alpha, run-length encoded: high nibble = value, low nibble = run length - 1.\n")
    f.write("constexpr int kFontPx = %d, kFontAtlasW = %d, kFontAtlasH = %d, kFontCellW = %d, kFontCellH = %d, kFontCols = %d, kFontGlyphs = %d, kFontAscent = %d;\n"
            % (px, aw, ah, cell_w, cell_h, cols, n, asc))
    f.write("constexpr uint8_t kFontAdvance[%d] = {%s};\n" % (n, ",".join(str(a) for a in adv)))
    f.write("constexpr uint8_t kFontRle[%d] = {\n" % len(out))
    for k in range(0, len(out), 24):
        f.write(",".join(str(b) for b in out[k:k+24]) + ",\n")
    f.write("};\n")
img.save("/home/claude/work/font_atlas.png")
print(aw, ah, cell_w, cell_h, len(out), "bytes RLE")
